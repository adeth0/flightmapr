// Two-letter IATA prefix fallback (used when the callsign starts
// with an IATA rather than ICAO code, e.g. "BA123"). Rare on ADS-B
// but common in scheduled items generated by airportService.
const IATA_PREFIXES = new Set(Object.values(ICAO_TO_IATA));

