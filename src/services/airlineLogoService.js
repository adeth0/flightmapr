function normaliseCallsign(value) {
  return String(value ?? '').trim().toUpperCase().replace(/\s+/g, '');
}

/**
 * Derive a best-effort IATA code from a callsign / airline name.
 * Returns null when no match is found.
 */
export function resolveAirlineIata(callsign, airlineName) {
  const cs = normaliseCallsign(callsign);
  if (cs.length >= 3) {
    const hit = ICAO_TO_IATA[cs.slice(0, 3)];
    if (hit) return hit;
  }
  if (cs.length >= 2 && IATA_PREFIXES.has(cs.slice(0, 2))) {
    return cs.slice(0, 2);
  }
  if (airlineName && NAME_TO_IATA[airlineName]) return NAME_TO_IATA[airlineName];
  return null;
}

/**
 * Build a logo URL for the resolved IATA code. Width/height in px.
 * Uses the pics.avs.io CDN (serves transparent PNGs, CORS-enabled).
 */
export function airlineLogoUrl(iata, w = 120, h = 40) {
  if (!iata) return null;
  return `https://pics.avs.io/${w}/${h}/${iata}.png`;
}

/**
 * Convenience helper — returns `{ iata, logoUrl, initials, hue }`.
 *   • `initials` + `hue` drive the letter-badge fallback (same visual
 *     language Sidebar.jsx already uses).
 *   • Callers can render <img> if `logoUrl` is non-null and attach an
 *     onError that swaps in the badge markup.
 */
export function getAirlineBrand(callsign, airlineName, size = { w: 120, h: 40 }) {
  const iata = resolveAirlineIata(callsign, airlineName);
  const name = airlineName && airlineName !== 'Unknown' ? airlineName : (iata ?? 'Airline');
  const initials = name.split(/\s+/).slice(0, 2).map((w) => w[0] ?? '').join('').toUpperCase() || '✈';
  const hue = [...name].reduce((h, c) => (h * 31 + c.charCodeAt(0)) % 360, 0);
  return {
    iata,
    logoUrl: airlineLogoUrl(iata, size.w, size.h),
    initials,
    hue,
  };
}
